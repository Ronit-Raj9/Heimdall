// Package pullagent is the server side of pull-mode agents (lane Y11,
// docs/pull-agents.md): an agent that runs in the customer's own process
// (heimdall.serve in the Python and TypeScript SDKs) and connects out to
// Heimdall, so nothing connects in to the customer's network.
//
// A run of a pull agent parks each turn on the Broker's queue for its org
// and agent name; the customer's process long-polls the queue with an org
// API token, takes the turn and posts the answer; the run's launcher
// long-polls for that answer. A run authenticates with a run token the
// adapter signs at plan time (Signer); the token names the org, the agent
// and the run and expires with the run's budget, so a run can only reach
// its own turns. The Broker also keeps the workspace tarballs remote coding
// agents download through signed, expiring URLs (repo in, patch out).
//
// Everything is in memory: a server restart fails the turns in flight, and
// the runs retry like any infrastructure error.
package pullagent

import (
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"errors"
	"os"
	"strconv"
	"strings"
	"sync"
	"time"
)

// EnvSigningKey holds the key run tokens and repository URLs are signed
// with. The server and every worker that plans pull runs must share it.
const EnvSigningKey = "HEIMDALL_PULL_SIGNING_KEY"

const tokenPrefix = "hpr1."

// Claims are what a run token says.
type Claims struct {
	Org   string `json:"o"`
	Agent string `json:"a"`
	Run   string `json:"r"`
	Exp   int64  `json:"e"` // unix seconds
}

// Signer signs and verifies run tokens and repository URLs.
type Signer struct {
	key       []byte
	ephemeral bool
}

// NewSigner returns a signer over key. A key shorter than 16 bytes is refused.
func NewSigner(key []byte) (*Signer, error) {
	if len(key) < 16 {
		return nil, errors.New("pull signing key is shorter than 16 bytes")
	}
	return &Signer{key: append([]byte(nil), key...)}, nil
}

var (
	defaultOnce   sync.Once
	defaultSigner *Signer
)

// DefaultSigner is the process's signer: the key in HEIMDALL_PULL_SIGNING_KEY,
// else a random key that lives as long as the process (enough for a local
// server that plans and serves its own runs; Ephemeral reports it).
func DefaultSigner() *Signer {
	defaultOnce.Do(func() {
		if k := strings.TrimSpace(os.Getenv(EnvSigningKey)); len(k) >= 16 {
			defaultSigner, _ = NewSigner([]byte(k))
			return
		}
		b := make([]byte, 32)
		if _, err := rand.Read(b); err != nil {
			panic("pullagent: random signing key: " + err.Error())
		}
		defaultSigner = &Signer{key: b, ephemeral: true}
	})
	return defaultSigner
}

// Ephemeral reports whether the key was generated by this process.
func (s *Signer) Ephemeral() bool { return s != nil && s.ephemeral }

func (s *Signer) mac(parts ...string) []byte {
	m := hmac.New(sha256.New, s.key)
	for _, p := range parts {
		m.Write([]byte(p))
		m.Write([]byte{0})
	}
	return m.Sum(nil)
}

// RunToken signs c.
func (s *Signer) RunToken(c Claims) (string, error) {
	body, err := json.Marshal(c)
	if err != nil {
		return "", err
	}
	enc := base64.RawURLEncoding.EncodeToString(body)
	return tokenPrefix + enc + "." + base64.RawURLEncoding.EncodeToString(s.mac("run", enc)), nil
}

// Token errors.
var (
	ErrBadToken     = errors.New("the run's pull token does not verify: the server and the worker that planned the run must share HEIMDALL_PULL_SIGNING_KEY")
	ErrExpiredToken = errors.New("the run's pull token expired")
)

// VerifyRun checks a run token and returns its claims.
func (s *Signer) VerifyRun(tok string, now time.Time) (Claims, error) {
	var c Claims
	rest, ok := strings.CutPrefix(tok, tokenPrefix)
	if !ok {
		return c, ErrBadToken
	}
	enc, sig, ok := strings.Cut(rest, ".")
	if !ok {
		return c, ErrBadToken
	}
	got, err := base64.RawURLEncoding.DecodeString(sig)
	if err != nil || !hmac.Equal(got, s.mac("run", enc)) {
		return c, ErrBadToken
	}
	body, err := base64.RawURLEncoding.DecodeString(enc)
	if err != nil || json.Unmarshal(body, &c) != nil || c.Run == "" || c.Agent == "" {
		return Claims{}, ErrBadToken
	}
	if now.Unix() > c.Exp {
		return Claims{}, ErrExpiredToken
	}
	return c, nil
}

// RepoSig signs a repository id and its expiry.
func (s *Signer) RepoSig(id string, exp int64) string {
	return hex.EncodeToString(s.mac("repo", id, strconv.FormatInt(exp, 10)))
}

// VerifyRepo checks a repository URL's signature and expiry.
func (s *Signer) VerifyRepo(id, exp, sig string, now time.Time) error {
	e, err := strconv.ParseInt(exp, 10, 64)
	if err != nil {
		return ErrBadRepoURL
	}
	got, err := hex.DecodeString(sig)
	if err != nil || !hmac.Equal(got, s.mac("repo", id, exp)) {
		return ErrBadRepoURL
	}
	if now.Unix() > e {
		return ErrRepoExpired
	}
	return nil
}

// Repository URL errors.
var (
	ErrBadRepoURL  = errors.New("the repository link is not valid")
	ErrRepoExpired = errors.New("the repository link expired")
)

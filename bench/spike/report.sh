## Design (section 13) corrections

1. **Pinned price file is mandatory, not a nicety (13.5).** Without `file://` datasheets a fresh gateway with no internet exits at boot. Add `mcp_library_sync_interval: 0` and `live_models_sync_interval: 0` to the gateway settings.
2. **Join key (13.4, S5) needs `store_raw_request_response: true` on the provider.** The provider's response id is not a row column; it lives in the detail row's `raw_response`. Without that flag the fallback is order plus usage. Error rows join by the proxy nonce in `raw_response`/`error_details`. Attempts group by `sha256(raw_request)` = ledger `req_sha256`.
3. **No forwarded request id.** Bifrost sends only `anthropic-version`, `content-type`, `content-length`, `user-agent: fasthttp`, `x-api-key` (plus `accept`, `cache-control`, `connection` on streams) upstream. A join via a forwarded header is not possible on stock v2.5.1.
4. **Weight is required on the VK provider config,** or plain model ids do not route (governance skips weightless candidates).
5. **`total_count` is not a completeness signal** without a bounded time window (matview lag). Page to a short page; pass `start_time`.
6. **Uncounted `GET /v1/models` traffic** comes from Bifrost itself on key create and on every provider PUT (2 per key). It has no row. "Every ledger entry matches a row" (13.4 step 2) must be restricted to counted lines plus client `count_tokens`/`models` calls, and a provider PUT mid-run would add proxy traffic.
7. **Management auth (13.2) is the setup token** in `X-Bifrost-Setup-Token`, from `BIFROST_SETUP_TOKEN`; the line range cited in DESIGN section 5 S2 (`server.go:3863-3867`) is `server.go:3745-3750` on the v2.5.1 tag.
8. **Streamed rows keep the whole upstream event sequence** in `raw_response` (with `store_raw_request_response: true`), including `tool_use` blocks and `input_json_delta` frames. S8's gateway-side tool-call count can be rebuilt from detail rows, not only from Claude Code's stream. Error rows have an empty `selected_key_name`/`selected_key_id`; the slot is in `attempt_trail[0].key_name`.
9. **List rows lack `attempt_trail`;** one detail fetch per row is required (confirms 13.4 step 3).
10. **"No row is `processing`" proves nothing on its own.** Rows are written in batches up to 5 s after the response and never showed as `processing`; an early poll sees zero rows and zero `processing`. The stop rule must be ledger-driven (row count and join cover every counted ledger line), and the gateway should set `logs_store.writer.batch_interval` low (for example `"500ms"`, untested).
11. The `list_models` row id may differ from the `x-bifrost-request-id` the client saw (see S5); key `count_tokens`/`list_models` joins on body hash and order, not on that header.


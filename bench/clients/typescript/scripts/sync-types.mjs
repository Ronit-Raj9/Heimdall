#!/usr/bin/env node
// Copies the UI's wire types (bench/ui/lib/types/bench.ts, which mirrors the
// Go types in bench/schemas) into src/types.ts, so the client and the UI read
// the API through one source of truth.
//
//   node scripts/sync-types.mjs          rewrite src/types.ts
//   node scripts/sync-types.mjs --check  exit 1 when src/types.ts is stale
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "..", "ui", "lib", "types", "bench.ts");
const target = join(here, "..", "src", "types.ts");
const header =
	"// Generated by scripts/sync-types.mjs from bench/ui/lib/types/bench.ts. Do not edit by hand.\n" +
	"// The UI file mirrors the Go types in bench/schemas; rerun the script after it changes.\n\n";

if (!existsSync(source)) {
	console.error(`sync-types: ${source} not found; run inside the Heimdall repository`);
	process.exit(2);
}
const want = header + readFileSync(source, "utf8");
if (process.argv.includes("--check")) {
	const have = existsSync(target) ? readFileSync(target, "utf8") : "";
	if (have !== want) {
		console.error("sync-types: src/types.ts is stale; run: node scripts/sync-types.mjs");
		process.exit(1);
	}
	process.exit(0);
}
writeFileSync(target, want);

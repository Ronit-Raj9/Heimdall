#!/usr/bin/env python3
"""Generate heimdall/models.py from the server's OpenAPI description.

The schemas in GET /api/bench/openapi.json are derived from the Go types by
reflection (bench/handlers/openapi.go), so the TypedDicts written here follow
the server without a second hand-written copy.

    python3 scripts/gen_models.py --url http://127.0.0.1:8090/api/bench/openapi.json
    python3 scripts/gen_models.py --file openapi.json
    python3 scripts/gen_models.py --file openapi.json --check   # exit 1 when models.py is stale
"""

import argparse
import json
import keyword
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "..", "heimdall", "models.py")

HEADER = '''"""Typed shapes of the Heimdall bench API.

Generated by scripts/gen_models.py from GET /api/bench/openapi.json, whose
schemas the server derives from its Go types. Do not edit by hand; run the
generator against a server built from the same tree instead.

Every JSON response also carries a top-level ``mode`` key (see ``Mode``); the
``*Response`` types add it.
"""

from __future__ import annotations

from typing import Any, Dict, List, Literal, Optional, TypedDict

Mode = Literal["live", "recorded", "synthetic"]
"""Where the data came from. Only live is a real measurement."""
'''


def py_type(schema):
    """Return the Python annotation for one JSON Schema."""
    if not isinstance(schema, dict):
        return "Any"
    ref = schema.get("$ref")
    if ref:
        return class_name(ref.rsplit("/", 1)[-1])
    any_of = schema.get("anyOf")
    if any_of:
        parts = [p for p in any_of if p.get("type") != "null"]
        if len(parts) == 1:
            return "Optional[%s]" % py_type(parts[0])
        return "Any"
    kind = schema.get("type")
    if kind == "string":
        return "str"
    if kind == "integer":
        return "int"
    if kind == "number":
        return "float"
    if kind == "boolean":
        return "bool"
    if kind == "array":
        return "List[%s]" % py_type(schema.get("items"))
    if kind == "object" and "additionalProperties" in schema:
        return "Dict[str, %s]" % py_type(schema["additionalProperties"])
    return "Any"


def response_types(doc):
    """Names of the components that some route answers as JSON."""
    names = set()
    for item in doc.get("paths", {}).values():
        for op in item.values():
            for status, resp in op.get("responses", {}).items():
                if not status.startswith("2"):
                    continue
                schema = resp.get("content", {}).get("application/json", {}).get("schema", {})
                for part in schema.get("allOf", []):
                    ref = part.get("$ref", "")
                    if ref and not ref.endswith("/ModeField"):
                        names.add(ref.rsplit("/", 1)[-1])  # component key; class_name() applies when emitted
    return names


# Names the generated module defines or imports itself.
RESERVED = {"Any", "Dict", "List", "Literal", "Optional", "TypedDict", "Mode"}


def class_name(name):
    """A component name as a Python class name."""
    return name + "_" if name in RESERVED or keyword.iskeyword(name) else name


def emit_component(name, schema):
    """Return the source of one TypedDict."""
    name = class_name(name)
    props = schema.get("properties", {}) or {}
    required = [k for k in sorted(props) if k in set(schema.get("required", []))]
    optional = [k for k in sorted(props) if k not in set(required)]
    if any(keyword.iskeyword(k) or not k.isidentifier() for k in props):
        # Keys that are not identifiers need the functional form, which has
        # no required/optional split before Python 3.11: all optional.
        fields = ", ".join("%r: %s" % (k, json.dumps(py_type(props[k]))) for k in sorted(props))
        return "%s = TypedDict(%r, {%s}, total=False)\n" % (name, name, fields)
    lines = []
    if required and optional:
        lines.append("class _%sRequired(TypedDict):" % name)
        lines += ["    %s: %s" % (k, py_type(props[k])) for k in required]
        lines.append("")
        lines.append("")
        lines.append("class %s(_%sRequired, total=False):" % (name, name))
        lines += ["    %s: %s" % (k, py_type(props[k])) for k in optional]
    elif required:
        lines.append("class %s(TypedDict):" % name)
        lines += ["    %s: %s" % (k, py_type(props[k])) for k in required]
    else:
        lines.append("class %s(TypedDict, total=False):" % name)
        lines += ["    %s: %s" % (k, py_type(props[k])) for k in optional] or ["    pass"]
    return "\n".join(lines) + "\n"


def generate(doc):
    """Return the full source of models.py for an OpenAPI document."""
    comps = doc["components"]["schemas"]
    out = [HEADER]
    for name in sorted(comps):
        if name == "ModeField":
            continue
        out.append("\n\n")
        out.append(emit_component(name, comps[name]))
    for key in sorted(response_types(doc)):
        name = class_name(key)
        if "mode" in (comps[key].get("properties") or {}):
            # The payload carries its own mode (schemas.Catalog).
            out.append("\n\n%sResponse = %s\n" % (key, name))
            continue
        out.append("\n\nclass %sResponse(%s):\n    mode: Mode\n" % (key, name))
    names = [class_name(n) for n in sorted(comps) if n != "ModeField"]
    names += ["%sResponse" % n for n in sorted(response_types(doc))]
    out.append("\n\n__all__ = [\n    \"Mode\",\n")
    out += ["    %r,\n" % n for n in names]
    out.append("]\n")
    return "".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--url", help="OpenAPI URL of a running server")
    src.add_argument("--file", help="OpenAPI JSON file")
    ap.add_argument("--check", action="store_true", help="exit 1 when models.py differs from what the document generates")
    ap.add_argument("--out", default=TARGET, help="output path")
    args = ap.parse_args(argv)
    if args.url:
        with urllib.request.urlopen(args.url, timeout=30) as resp:
            doc = json.load(resp)
    else:
        with open(args.file, encoding="utf-8") as fh:
            doc = json.load(fh)
    text = generate(doc)
    if args.check:
        try:
            with open(args.out, encoding="utf-8") as fh:
                current = fh.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            sys.stderr.write("%s is stale: regenerate it with scripts/gen_models.py\n" % os.path.normpath(args.out))
            return 1
        return 0
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())

// checkYAML is one entry of checks.yaml as package taskchecks reads it.
type checkYAML struct {
	ID          string         `yaml:"id"`
	Description string         `yaml:"description,omitempty"`
	Required    bool           `yaml:"required,omitempty"`
	ToolCalled  map[string]any `yaml:"tool_called,omitempty"`
	ReplyRubric string         `yaml:"reply_rubric,omitempty"`
}

var slugRE = regexp.MustCompile(`[^a-z0-9]+`)

func slug(s string) string {
	out := strings.Trim(slugRE.ReplaceAllString(strings.ToLower(s), "-"), "-")
	if len(out) > 48 {
		out = out[:48]
	}
	if out == "" {
		out = "tool"
	}
	return out
}

// failedTools are the distinct tools that returned an error, in order, each
// with its first error text.
func failedTools(s *traceimport.Session) (names []string, errs map[string]string) {
	errs = map[string]string{}
	for _, c := range s.ToolCalls {
		if !c.IsError || c.Name == "" || slices.Contains(names, c.Name) {
			continue
		}
		names = append(names, c.Name)
		errs[c.Name] = oneLine(firstNonEmpty(c.Error, c.Result), 160)
	}
	return names, errs
}

// SuggestedRubric is the generated "what should have happened" a person
// edits: the request resolved without the failure Maxim flagged, and a
// reply like the recorded one failing.
func SuggestedRubric(s *traceimport.Session, c *Cluster) string {
	var b strings.Builder
	b.WriteString("The agent resolves the request without the failure seen in production")
	if c != nil && c.Label != "" {
		b.WriteString(" (" + c.Label + ")")
	}
	b.WriteString(".")
	if c != nil && len(c.Reasons) > 0 {
		b.WriteString(" Maxim flagged it: " + oneLine(strings.Join(c.Reasons, "; "), 400) + ".")
	}
	if ans := strings.TrimSpace(s.FinalAnswer); ans != "" {
		b.WriteString(" A reply like the recorded one fails: \"" + oneLine(ans, 300) + "\".")
	}
	return b.String()
}

// ChecksYAML writes checks.yaml for a session: every tool that failed in
// production must now return a result without an error, and the reply must
// meet the rubric. reviewed says whether a person confirmed it.
func ChecksYAML(taskID string, s *traceimport.Session, c *Cluster, rubric string, reviewedBy string) ([]byte, []string, error) {
	tools, errs := failedTools(s)
	var list []checkYAML
	used := map[string]bool{}
	for _, t := range tools {
		id := "succeeds-" + slug(t)
		for n := 2; used[id]; n++ {
			id = fmt.Sprintf("succeeds-%s-%d", slug(t), n)
		}
		used[id] = true
		desc := "the agent gets a result from " + t + " without an error"
		if e := errs[t]; e != "" {
			desc += " (in production it failed: " + e + ")"
		}
		list = append(list, checkYAML{ID: id, Required: true, Description: desc,
			ToolCalled: map[string]any{"tool": t, "succeeded": true}})
	}
	if strings.TrimSpace(rubric) != "" {
		list = append(list, checkYAML{ID: "reply", Description: "what should have happened", ReplyRubric: strings.TrimSpace(rubric)})
	}
	ids := make([]string, 0, len(list))
	for _, ch := range list {
		ids = append(ids, ch.ID)
	}
	doc := struct {
		Version int         `yaml:"version"`
		Checks  []checkYAML `yaml:"checks"`
	}{1, list}
	body, err := yaml.Marshal(doc)
	if err != nil {
		return nil, nil, err
	}
	var h strings.Builder
	fmt.Fprintf(&h, "# Checks of %s, generated by Heimdall from a Maxim production failure", taskID)
	if c != nil {
		fmt.Fprintf(&h, "\n# (%s, %d occurrences).", oneLine(c.Label, 100), c.Occurrences)
	} else {
		h.WriteString(".")
	}
	if reviewedBy == "" {
		h.WriteString("\n# Generated, pending review: a person confirms what should have happened")
		h.WriteString("\n# before the readiness check runs.")
	} else {
		h.WriteString("\n# Generated, then reviewed and accepted by " + oneLine(reviewedBy, 80) + ".")
	}
	h.WriteString("\n# The checks grader reads this file (docs/declarative-checks.md).\n")
	return append([]byte(h.String()), body...), ids, nil
}

// scenarioRow is the Y14 scenario row shape (scaffold.ScenarioRow).
type scenarioRow struct {
	ID          string   `json:"id"`
	Title       string   `json:"title"`
	Opening     string   `json:"opening_message"`
	Goal        string   `json:"persona_goal"`
	Facts       []string `json:"facts"`
	ReplyRubric string   `json:"reply_rubric,omitempty"`
	Category    string   `json:"category"`
	Generated   bool     `json:"generated"`
	ReviewedBy  string   `json:"reviewed_by,omitempty"`
}

// ScenarioJSON writes the scenario row of a session: the first request
// opens the chat, later user turns become facts the simulated user knows.
func ScenarioJSON(taskID string, s *traceimport.Session, c *Cluster, rubric, reviewedBy string) ([]byte, error) {
	reqs := s.Requests()
	row := scenarioRow{ID: taskID, Title: oneLine(s.FirstRequest(), 80), Opening: strings.TrimSpace(s.FirstRequest()),
		Facts: []string{}, ReplyRubric: strings.TrimSpace(rubric), Category: "production-failure", Generated: true, ReviewedBy: reviewedBy}
	row.Goal = "Get this done: " + oneLine(s.FirstRequest(), 200)
	for _, r := range reqs[min(1, len(reqs)):] {
		row.Facts = append(row.Facts, "Later in the chat the user said: "+oneLine(r, 400))
	}
	if c != nil {
		row.Category = "production-failure: " + oneLine(c.Label, 80)
	}
	b, err := json.MarshalIndent(row, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

func firstNonEmpty(v ...string) string {
	for _, s := range v {
		if strings.TrimSpace(s) != "" {
			return s
		}
	}
	return ""
}

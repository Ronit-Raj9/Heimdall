package scaffold

import (
	"encoding/json"
	"strings"
)

// ScriptStep is one step of a generated control script: Say sends a
// message to the simulated customer (respond_to_user on the customer
// service), otherwise Tool is called on Server with Args.
type ScriptStep struct {
	Say    string         `json:"say,omitempty"`
	Server string         `json:"server,omitempty"`
	Tool   string         `json:"tool,omitempty"`
	Args   map[string]any `json:"args,omitempty"`
}

// MCPControlScript is a control script (run in the agent's place with the
// task's services up) that plays steps in order through the same MCP
// servers an agent gets (BENCH_MCP_SERVERS). customer names the simulated
// customer's service ("" when the task has none). With keepGoing a tool
// error is printed and the script goes on (a mutant may call a tool the
// service refuses); without it the script stops on the first error, so a
// reference that no longer fits the service fails loudly. The steps are
// embedded as JSON, so no step text is ever read as code.
func MCPControlScript(header, customer string, steps []ScriptStep, keepGoing bool) []byte {
	plan, _ := json.Marshal(steps)
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	for _, ln := range strings.Split(strings.TrimSpace(header), "\n") {
		b.WriteString("# " + strings.TrimSpace(ln) + "\n")
	}
	b.WriteString("# Generated by Heimdall; the steps are the JSON in STEPS below.\n")
	b.WriteString("exec python3 -I - <<'PY'\n")
	b.WriteString(mcpClientPy)
	b.WriteString("\nCUSTOMER = " + pyString(customer) + "\n")
	if keepGoing {
		b.WriteString("KEEP_GOING = True\n")
	} else {
		b.WriteString("KEEP_GOING = False\n")
	}
	b.WriteString("STEPS = json.loads(" + pyString(string(plan)) + ")\n")
	b.WriteString(mcpRunPy)
	b.WriteString("PY\n")
	return []byte(b.String())
}

// pyString is s as a Python string literal (a JSON string is one, and the
// heredoc is quoted, so the shell expands nothing).
func pyString(s string) string {
	out, _ := json.Marshal(s)
	return string(out)
}

const mcpClientPy = `import json, os, sys, urllib.request

servers = json.loads(os.environ.get("BENCH_MCP_SERVERS") or "{}")


def url(service):
    return (servers.get(service) or {}).get("url") or f"http://toolproxy:9200/s/{service}/mcp"


class Client:
    def __init__(self, service):
        self.url, self.session, self.next_id = url(service), {}, 0
        self.rpc("initialize", {"protocolVersion": "2025-06-18", "capabilities": {}, "clientInfo": {"name": "control", "version": "1"}})
        self.rpc("notifications/initialized", notify=True)

    def rpc(self, method, params=None, notify=False):
        msg = {"jsonrpc": "2.0", "method": method, "params": params or {}}
        if not notify:
            self.next_id += 1
            msg["id"] = self.next_id
        headers = {"Content-Type": "application/json", "Accept": "application/json, text/event-stream"}
        headers.update(self.session)
        req = urllib.request.Request(self.url, data=json.dumps(msg).encode(), headers=headers, method="POST")
        with urllib.request.urlopen(req, timeout=60) as resp:
            if resp.headers.get("Mcp-Session-Id"):
                self.session["Mcp-Session-Id"] = resp.headers["Mcp-Session-Id"]
            body = resp.read().decode()
        if notify:
            return None
        if body.lstrip().startswith("data:") or "\ndata:" in body:
            body = [l[5:] for l in body.splitlines() if l.startswith("data:")][-1]
        answer = json.loads(body)
        if "error" in answer:
            raise RuntimeError(f"{method}: {answer['error']}")
        return answer["result"]

    def call(self, tool, args):
        result = self.rpc("tools/call", {"name": tool, "arguments": args})
        text = "".join(c.get("text", "") for c in result.get("content", []))
        if result.get("isError"):
            raise RuntimeError(f"{tool}: {text}")
        return text
`

const mcpRunPy = `clients = {}


def client(service):
    if service not in clients:
        clients[service] = Client(service)
    return clients[service]


for step in STEPS:
    try:
        if step.get("say") is not None:
            if not CUSTOMER:
                print("agent:", step["say"])
                continue
            print("customer:", client(CUSTOMER).call("respond_to_user", {"message": step["say"]}))
        else:
            print(step["tool"] + ":", client(step["server"]).call(step["tool"], step.get("args") or {}))
    except Exception as e:  # noqa: BLE001
        if not KEEP_GOING:
            sys.exit(str(e))
        print("error (kept going):", e, file=sys.stderr)
`

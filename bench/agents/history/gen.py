"""Writes history_gen.go: the sha256 of every version, in git history, of a
built-in agent file (bench/agents/*.yaml, bench/agents/images/**,
bench/examples/frameworks/**) that still ships, with its current path.
Run from the repository root: python3 -I bench/agents/history/gen.py"""
import hashlib, os, subprocess, sys

roots = ["bench/agents/images", "bench/examples/frameworks"]
def git(*a, raw=False):
    out = subprocess.run(["git", *a], check=True, capture_output=True).stdout
    return out if raw else out.decode()

current = set()
for line in git("ls-files", "bench/agents", "bench/examples/frameworks").splitlines():
    rel = line[len("bench/"):]
    top = line.count("/") == 2 and line.startswith("bench/agents/") and line.endswith(".yaml")
    if top or any(line.startswith(r + "/") for r in roots):
        if not line.endswith(".go"):
            current.add(line)
pairs = set()
for path in sorted(current):
    for c in git("log", "--all", "--format=%H", "--", path).split():
        try:
            b = git("show", f"{c}:{path}", raw=True)
        except subprocess.CalledProcessError:
            continue
        pairs.add((hashlib.sha256(b).hexdigest(), path[len("bench/"):]))
    b = open(path, "rb").read()
    pairs.add((hashlib.sha256(b).hexdigest(), path[len("bench/"):]))
out = ["// Code generated by history/gen.py; DO NOT EDIT.", "", "package history", "",
       "// versions lists sha256 and current path of every shipped version of a", "// built-in agent file.",
       "var versions = [][2]string{"]
out += [f'\t{{"{h}", "{p}"}},' for h, p in sorted(pairs, key=lambda x: (x[1], x[0]))]
out += ["}", ""]
open("bench/agents/history/history_gen.go", "w").write("\n".join(out))
print(len(pairs), "versions of", len(current), "files")
